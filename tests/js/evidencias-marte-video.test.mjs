import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const core=require('../../static/js/cinematica.js');
const moon=require('../../static/js/luna-mision.js');
const root=new URL('../../',import.meta.url);
test('cada ficha lunar tiene imagen local y referencias disponibles',()=>{for(const [id,c] of Object.entries(moon.CARDS)){assert.ok(c.photo,id);for(const ph of [c.photo,c.photo.related].filter(Boolean)){assert.ok(existsSync(new URL(ph.src.slice(1),root)),ph.src);assert.ok(ph.caption.es&&ph.caption.en);}}});
test('Marte usa un video local distinto y subtitulos consistentes',()=>{const d=core.VIDEOS.mars_intro;assert.notEqual(d.src,core.VIDEOS.rock_roll_intro.src);assert.ok(existsSync(new URL(d.src.slice(1),root)));for(const l of ['es','en'])assert.equal(readFileSync(new URL(d.tracks[l].slice(1),root),'utf8').replace(/\r\n/g,'\n'),core.toVTT('mars_intro',l));assert.ok(d.cues.every(c=>c[1]<=d.duration));});
